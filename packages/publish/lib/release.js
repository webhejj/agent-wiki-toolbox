/**
 * Build a wiki site for publication, into `<site>/release`.
 *
 * A RELEASE IS THE BUILD OUTPUT ITSELF, kept on disk — not a tag, not a pointer
 * to a commit, and nothing enters git. A wiki is edited daily, so a release
 * marker on that history would be noise; what other wikis actually read is a
 * built directory. That is why this command exists rather than a documented
 * `git tag` ritual.
 *
 * PUBLISH MODE IS A BUILD WITHOUT `--serve`. There is no publish flag: the
 * cross-wiki resolver picks its mode from `ctx.argv.serve`, so a build without
 * it emits every registry entry's `published` base URL, and a dev server emits
 * `dev` ones. The mode being unforgettable is the point — see index.js.
 *
 * IT BUILDS INTO A STAGING DIRECTORY AND RENAMES. Quartz cleans and rewrites
 * its output directory in full before it can know whether the build succeeds,
 * so building straight into `release/` would let a build that dies halfway
 * destroy the release that was standing — the one thing other wikis resolve
 * their links against. Staging is a sibling of the release, so the swap is a
 * rename on one filesystem rather than a copy.
 *
 * IT REFUSES TO BUILD OVER `build/dev`, which is the dev server's output.
 * Publish mode over a dev build silently rewrites every cross-wiki link to its
 * published form and vice versa; the pages keep serving and every one returns
 * 200, so the damage is invisible. This avoids the same trap by building into a
 * staging directory and renaming it into place.
 *
 * IT ALSO BUILDS A HANDOFF COPY (`--offline`), for readers who have no server
 * at all — a folder to zip and send, opened by double-clicking index.html on any
 * machine. Two things separate that from a release, and both are unavoidable
 * rather than chosen: `file://` runs no external module script and blocks
 * `fetch`, so every piece of Quartz's JavaScript is dead there; and it has no
 * `try $uri.html` layer, so Quartz's extensionless links resolve to nothing. The
 * first is answered by building with the browser-only plugins off, so the pages
 * carry no dead furniture; the second by rewriting every href to a real file
 * afterwards, because Quartz cannot be configured to emit the extension —
 * `transformLink` drops it unconditionally, and the links in the page chrome are
 * generated by components at render time, out of reach of any transformer.
 *
 * Usage, from anywhere inside a project (`awt` resolves --wiki and --site from
 * the project's awt.config.mjs; the legacy `docs/wiki` + `site` still resolves):
 *     awt site publish                        # build, then swap into build/published/<slug>
 *     awt site publish --offline              # a zip-and-send copy, into build/handoff
 *     awt site publish --wiki path --site path
 *     awt site publish --out path             # somewhere other than build/published/<slug>
 *     awt site publish --nginx                # print a server block and exit
 *
 * The output is static HTML and assets; nothing of Quartz runs at serve time.
 * The one thing a host must do is try `$uri.html` before returning 404, because
 * Quartz emits extensionless URLs — the same resolution rule `awt check`
 * applies on disk, so a site that passes the check is a site nginx serves.
 *
 * Needs `node` and a Quartz clone set up by `awt site setup`.
 */

