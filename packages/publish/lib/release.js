const CANONICAL_CONFIG = `../../${DERIVED_CONFIG}`

function run(cmd, args, opts = {}) {
  return spawnSync(cmd, args, { encoding: "utf8", env: CLEAN_ENV, ...opts })
}

function die(msg) {
  console.error(msg)
  process.exit(2)
}

/** Every file under `dir`, as [count, bytes]. */
function measure(dir) {
  let files = 0
  let pages = 0
  let bytes = 0
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name)
    if (e.isDirectory()) {
      const [f, pg, b] = measure(p)
      files += f
      pages += pg
      bytes += b
    } else if (e.isFile()) {
      files++
      if (e.name.endsWith(".html")) pages++
      bytes += fs.statSync(p).size
    }
  }
  return [files, pages, bytes]
}

/** The shorter of the absolute and cwd-relative forms, so hints stay readable. */
function show(p) {
  const rel = path.relative(process.cwd(), p)
  return rel && rel.length < p.length && !rel.startsWith("..") ? rel : p
}

function mb(bytes) {
  return `${(bytes / 1024 / 1024).toFixed(1)} MB`
}

/**
 * Warn about a base URL that only makes sense locally. Quartz writes it into
 * absolute URLs — the sitemap, the RSS feed, `og:` tags — which a reader never
 * clicks and a crawler always does, so a localhost value here fails silently and
 * only off-site. Read from the derived config, which is what the build used.
 */
function checkBaseUrl(config, target) {
  // A target named on the command line or in the declaration is a deliberate address, local or not.
  if (target) return
  const value = String(config?.configuration?.baseUrl ?? "").trim()
  if (!value || value === "null" || /^(https?:\/\/)?(localhost|127\.0\.0\.1)\b/.test(value)) {
    say(
      `\n⚠ baseUrl is ${value ? `"${value}"` : "unset"}. The sitemap, RSS and og: tags in this\n` +
        "  release carry it. Declare site.baseUrl in awt.config.mjs as the host that serves the release.",
    )
  }
}

/** The wiki's own name, for the note that travels with a handoff copy. */
function siteTitle(config) {
  const value = String(config?.configuration?.pageTitle ?? "").trim()
  return value || "wiki"
}

/** A server block for the host rule Quartz's extensionless URLs need. */
function nginx(root) {
  return `# Quartz output is static: nothing of it runs at serve time. The one rule a
# host must apply is trying $uri.html before 404, because Quartz emits
# extensionless URLs. Without it every internal link 404s.
server {
    listen 80;
    server_name wiki.example.org;

    root ${root};
    index index.html;

    location / {
        try_files $uri $uri.html $uri/index.html =404;
    }

    # Quartz fingerprints its own CSS and JS (component-<hash>.css,
    # postscript-<hash>.js), so those are safe to cache hard. Nothing else is:
    # the pages, static/contentIndex.json and the feeds keep their names and are
    # rewritten by every build.
    location ~ "-[0-9a-f]{8}\\.(css|js)$" {
        expires 1y;
        add_header Cache-Control "public, immutable";
    }

    error_page 404 /404.html;
}`
}

/**
 * Quartz reads its config from `<cwd>/quartz.config.yaml` and nothing else —
 * there is no --config flag — so building with a different plugin set means
 * repointing the symlink `awt site setup` created, for the duration of one
 * build. Restored in a `finally`, and verified afterwards.
 *
 * The danger this creates is a wrong-config build that looks right, which is why
 * `assertCanonicalConfig` runs before an ordinary publish: a run killed between
 * the relink and the restore cannot silently produce a release built as a
 * handoff copy — the next publish refuses instead.
 */
function withConfig(quartz, configName, fn) {
  const link = path.join(quartz, "quartz.config.yaml")
  if (!configName) return fn()
  fs.rmSync(link, { force: true })
  fs.symlinkSync(`../../${configName}`, link)
  try {
    return fn()
  } finally {
    fs.rmSync(link, { force: true })
    fs.symlinkSync(CANONICAL_CONFIG, link)
  }
}

function assertCanonicalConfig(quartz) {
  const link = path.join(quartz, "quartz.config.yaml")
  const stat = fs.lstatSync(link, { throwIfNoEntry: false })
  // A real file there is somebody's own arrangement, not ours to judge; only a
  // symlink pointing somewhere unexpected means an offline build left it behind.
  if (!stat?.isSymbolicLink()) return
  const target = fs.readlinkSync(link)
  if (target !== CANONICAL_CONFIG) {
    die(
      `${link}\n  points at ${target}, not ${CANONICAL_CONFIG}.\n` +
        "An interrupted --offline build leaves it that way, and publishing now would\n" +
        "build a release with the handoff plugin set and no sign of it. Run\n" +
        "`awt site setup` to put it back.",
    )
  }
}

function build(quartz, wiki, out, configName) {
  sayPart(
    configName
      ? `building (offline mode, ${configName}) ... `
      : "building (publish mode, no --serve) ... ",
  )
  const b = withConfig(quartz, configName, () =>
    run("node", ["quartz/bootstrap-cli.mjs", "build", "-d", path.relative(quartz, wiki), "-o", out], {
      cwd: quartz,
    }),
  )
  if (b.status !== 0) {
    say("FAILED")
    die(
      `quartz build failed. The standing release is untouched; the build is left at ${show(out)}:\n` +
        ((b.stdout ?? "") + (b.stderr ?? "")).slice(-2000),
    )
  }
  say("ok")
}

/**
 * A release other wikis can resolve against needs more than "the build exited
 * 0": `contentIndex.json` is the file a dependent wiki's registry reads by path,
 * so a release missing it resolves nothing and warns in someone else's build.
 * Checked before the swap, while the previous release is still standing.
 */
export function verify(staging, offline) {
  const standing = `The standing release is untouched; the build is left at ${show(staging)}.`
  // contentIndex.json is what a dependent wiki's registry reads by path; a
  // handoff copy has no dependents, and nothing offline can fetch it anyway.
  const required = offline ? ["index.html"] : ["index.html", path.join("static", "contentIndex.json")]
  for (const r of required) {
    if (!fs.existsSync(path.join(staging, r))) {
      die(
        `the build produced no ${r}; not swapping.\n` +
          `Other wikis resolve links against it.\n${standing}`,
      )
    }
  }
  const [files, pages, bytes] = measure(staging)
  if (pages === 0) die(`the build produced no pages; not swapping.\n${standing}`)
  say(`  ${pages} pages, ${files} files, ${mb(bytes)}`)
  return { files, pages, bytes }
}

/**
 * Swap staging into place, keeping what was there as a hidden `-prev` beside it. Two
 * renames on one filesystem: the window in which the release path does not
 * exist is between them, and a copy would have no such property at all.
 *
 * The previous release is kept rather than deleted — it is the only copy of what
 * the site served a minute ago, and rolling back is then a rename rather than a
 * rebuild from a working tree that has since moved on.
 */
export function swap(staging, out, prev) {
  fs.rmSync(prev, { recursive: true, force: true })
  const had = fs.existsSync(out)
  if (had) fs.renameSync(out, prev)
  fs.renameSync(staging, out)
  return had
}


