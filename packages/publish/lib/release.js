/**
 * The config a handoff build uses: the project's own `quartz.offline.yaml` if it
 * has one, else the derived config with the browser-only plugins turned off.
 * Derived by default because the interesting choice is *which* plugins those
 * are, and that answer is the same in every project; a project that disagrees
 * writes the file and owns it from then on.
 *
 * Written with the `yaml` inside the Quartz install — the same parser Quartz
 * reads the config with, so this cannot disagree with it about what the file says.
 *
 * Returns the file name, relative to `site/`, since that is what the symlink
 * inside the install has to name.
 */
export async function offlineConfig(site, quartz, derived) {
  const own = "quartz.offline.yaml"
  if (fs.existsSync(path.join(site, own))) {
    say(`config: ${own} (the project's own)`)
    return own
  }

  const { stringify } = await loadFromQuartz(quartz, "yaml", die)
  const config = structuredClone(derived ?? {})

  config.configuration ??= {}
  // Both are progressive enhancement over `file://` and worse than useless
  // there: the SPA router would intercept clicks it cannot then service.
  config.configuration.enableSPA = false
  config.configuration.enablePopovers = false

  const off = []
  for (const plugin of config.plugins ?? []) {
    const source = typeof plugin.source === "string" ? plugin.source : plugin.source?.name
    const name = String(source ?? "").split("/").pop()
    if (BROWSER_ONLY_PLUGINS.includes(name) && plugin.enabled !== false) {
      plugin.enabled = false
      off.push(name)
    }
  }

  const generated = OFFLINE
  ensureBuildDir(site)
  fs.writeFileSync(
    path.join(site, generated),
    "# GENERATED by awt site publish --offline. Do not edit: it is rewritten on\n" +
      "# every offline build, and the comments in quartz.config.yaml are lost in\n" +
      "# the round trip. To take this over, copy it to quartz.offline.yaml;\n" +
      "# awt site publish uses that instead, and never touches it.\n" +
      stringify(config),
  )
  say(`config: ${generated} (derived; ${off.length ? off.join(", ") + " off" : "nothing to turn off"})`)
  return generated
}

/**
 * Rewrite an ordinary Quartz build into one that opens from `file://`.
 *
 * `file://` has no host applying `try $uri.html`, so an extensionless href
 * resolves to nothing at all — and Quartz has no setting for the extension.
 * Every link exists in one form only in the emitted HTML, which is why this
 * happens here rather than in a plugin: the links in breadcrumbs, backlinks,
 * folder listings and the table of contents are built by components at render
 * time, after every transformer has run.
 *
 * Attributes are rewritten in place rather than by parsing and re-serialising
 * the document, so nothing else in the file can change: an HTML round trip
 * normalises entities and void elements, and the diff would be unreviewable.
 *
 * A LINK THAT DOES NOT RESOLVE IS NOT AUTOMATICALLY A DEFECT. Most are
 * placeholders — `[[notes]]` nobody has written yet, which every working wiki
 * has a backlog of, and which Quartz itself marks `class="… broken"`. Failing on
 * those would mean no wiki with a backlog could ever be handed to a reader; it is
 * the same mistake as asserting zero broken links, which `awt check` exists to
 * not make. They are neutralised instead: the destination moves to
 * `data-unresolved-href`, so the text still reads but nothing lands the reviewer
 * on a browser error page they cannot interpret.
 *
 * A missing `src` is treated as a defect and does fail, because an asset the
 * build was supposed to emit and did not is a broken build, not a backlog.
 */
export function toFileUrls(root) {
  const walk = (d) =>
    fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => {
      const p = path.join(d, e.name)
      return e.isDirectory() ? walk(p) : [p]
    })
  const all = walk(root)
  const pages = all.filter((f) => f.endsWith(".html"))

  // What a browser can actually open from disk: an exact file, nothing else.
  // A directory is not it — `file://` shows a listing rather than its index.
  const resolve = (dir, link) => {
    const disk = path.join(dir, decodeURIComponent(link))
    if (fs.existsSync(disk) && fs.statSync(disk).isFile()) return link
    if (fs.existsSync(disk + ".html")) return link + ".html"
    if (fs.existsSync(path.join(disk, "index.html"))) return link.replace(/\/?$/, "/") + "index.html"
    return null
  }

  const external = (u) => !u || /^[a-z][a-z0-9+.-]*:/i.test(u) || u.startsWith("#") || u.startsWith("//")

  let rewritten = 0
  let scripts = 0
  let neutralised = 0
  const placeholders = new Set()
  const dangling = []
  const missingAssets = []

  for (const page of pages) {
    const dir = path.dirname(page)
    const before = fs.readFileSync(page, "utf8")
    // Strip the scripts outright. None of them can run from `file://`, and a
    // handoff copy that provably carries no JavaScript is easier to hand over
    // than one that carries some which happens not to execute.
    let html = before.replace(/<script\b[^>]*>[\s\S]*?<\/script>/gi, () => {
      scripts++
      return ""
    })
    // Quartz preloads its scripts as well as loading them. Left behind, the
    // preload keeps the bundle it points at alive as a referenced file, so a
    // copy advertised as carrying no JavaScript still ships some.
    html = html.replace(/<link\b[^>]*\b(?:as="script"|rel="modulepreload")[^>]*>/gi, () => {
      scripts++
      return ""
    })

    const rewrite = (whole, attr, url, tag) => {
      if (external(url)) return whole
      const [link, anchor = ""] = url.split(/(#.*)$/)
      if (!link) return whole
      const target = resolve(dir, link)
      if (target) {
        if (target === link) return whole
        rewritten++
        return `${attr}="${target}${anchor}"`
      }

      if (attr === "src") {
        missingAssets.push(`${path.relative(root, page)} -> ${url}`)
        return whole
      }
      // Quartz already knows: it renders a link to an unwritten note with the
      // `broken` class. Trusting that mark rather than re-deciding keeps this
      // agreeing with the renderer instead of second-guessing it.
      if (/\bclass="[^"]*\bbroken\b/.test(tag)) {
        placeholders.add(link.replace(/^(\.\.?\/)+/, ""))
      } else {
        dangling.push(`${path.relative(root, page)} -> ${url}`)
      }
      neutralised++
      return `data-unresolved-href="${url}"`
    }

    html = html.replace(/(?<![\w-])(href|src)="([^"]*)"/g, (whole, attr, url, offset) => {
      // The enclosing tag, so the class attribute is visible whether it sits
      // before or after the attribute being rewritten.
      const start = html.lastIndexOf("<", offset)
      const end = html.indexOf(">", offset)
      const tag = start === -1 || end === -1 ? "" : html.slice(start, end + 1)
      return rewrite(whole, attr, url, tag)
    })
    // An alias emits a meta refresh, whose destination is a link like any other
    // and would otherwise send the reader to a page that does not exist.
    html = html.replace(
      /(content)="(\d+\s*;\s*url=)([^"]+)"/gi,
      (whole, attr, prefix, url) => {
        const inner = rewrite(`${attr}="${url}"`, attr, url)
        return inner === `${attr}="${url}"` ? whole : `${attr}="${prefix}${inner.slice(attr.length + 2, -1)}"`
      },
    )

    if (html !== before) fs.writeFileSync(page, html)
  }

  // With every script tag gone, the chunks they loaded are unreachable weight.
  let removed = 0
  const referenced = new Set()
  for (const page of pages) {
    for (const m of fs.readFileSync(page, "utf8").matchAll(/(?<![\w-])(?:href|src)="([^"]+)"/g)) {
      if (!external(m[1])) {
        referenced.add(path.resolve(path.dirname(page), decodeURIComponent(m[1].split("#")[0])))
      }
    }
  }
  for (const f of all) {
    if (f.endsWith(".js") && !referenced.has(path.resolve(f))) {
      fs.rmSync(f)
      removed++
    }
  }
  for (const d of walk_dirs(root)) {
    if (fs.readdirSync(d).length === 0) fs.rmdirSync(d)
  }

  return {
    pages: pages.length,
    rewritten,
    scripts,
    removed,
    neutralised,
    placeholders: [...placeholders].sort(),
    dangling,
    missingAssets,
  }
}

/**
 * Make the front door a real page.
 *
 * A wiki whose landing note is not literally `index.md` — `README.md`, say —
 * gets an `index.html` from Quartz that is a 246-byte `<meta http-equiv=
 * "refresh">` stub pointing at the real page. Over HTTP that is invisible. Handed
 * to a reviewer as a folder, it is the first thing they double-click, and a
 * refresh is exactly the kind of navigation a browser may decline to perform
 * from `file://` — leaving a blank window with nothing to click and no error to
 * read. Inlining the target removes the hop entirely.
 *
 * Only when the target sits in the same directory, because every relative link
 * inside it is written from that directory's depth and would otherwise resolve
 * one level off — a page that loads with every link subtly wrong is worse than
 * a redirect.
 */
function inlineRootIndex(root) {
  const index = path.join(root, "index.html")
  if (!fs.existsSync(index)) return null
  const html = fs.readFileSync(index, "utf8")
  const m = /<meta\s+http-equiv="refresh"\s+content="\d+\s*;\s*url=([^"]+)"/i.exec(html)
  if (!m) return null
  // A stub is head-only. Anything with real content is a page in its own right.
  if (/<body[^>]*>\s*\S/i.test(html)) return null

  const target = decodeURIComponent(m[1].split("#")[0])
  if (path.dirname(target) !== "." || !fs.existsSync(path.join(root, target))) return null

  fs.copyFileSync(path.join(root, target), index)
  return target
}

/** Directories under `root`, deepest first, so emptied ones can be dropped. */
function walk_dirs(root) {
  const out = []
  const visit = (d) => {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      if (e.isDirectory()) {
        const p = path.join(d, e.name)
        visit(p)
        out.push(p)
      }
    }
  }
  visit(root)
  return out
}

/**
 * Every reference a browser will follow must be a file that exists. This is the
 * whole guarantee of a handoff copy — there is no server to be forgiving, and a
 * reader who clicks into a "file not found" has no way to tell it from the
 * document being broken.
 */
export function verifyFileUrls(root) {
  const bad = []
  let total = 0
  const walk = (d) =>
    fs.readdirSync(d, { withFileTypes: true }).flatMap((e) => {
      const p = path.join(d, e.name)
      return e.isDirectory() ? walk(p) : p.endsWith(".html") ? [p] : []
    })
  for (const page of walk(root)) {
    const dir = path.dirname(page)
    for (const m of fs.readFileSync(page, "utf8").matchAll(/(?<![\w-])(?:href|src)="([^"]+)"/g)) {
      const url = m[1]
      if (!url || /^[a-z][a-z0-9+.-]*:/i.test(url) || url.startsWith("#") || url.startsWith("//")) continue
      const link = url.split("#")[0]
      if (!link) continue
      total++
      const disk = path.join(dir, decodeURIComponent(link))
      if (!fs.existsSync(disk) || !fs.statSync(disk).isFile()) bad.push(`${path.relative(root, page)} -> ${url}`)
    }
  }
  return { total, bad }
}

/** Where a release is recorded in its own output, read back by `verify` and the server config. */
export const RELEASE_RECORD = path.join("static", "awtRelease.json")

/**
 * The target a build is for and where it lands, from the flags, the declaration and the machine.
 *
 * A base comes from `--base`, or from `site.baseUrl`, which is the project's standing target. With
 * neither, a target is named: `--target`, then `$AWT_TARGET`, then `site.target`, then the machine's
 * `default-target`, and its base is read from `targets.yaml`. A named target hosts several wikis, so
 * the wiki needs a mount under it.
 *
 * Every target lands in `build/published/<slug>`, one directory per base, so two bases built from one
 * checkout do not overwrite each other. A build with no base anywhere is `build/published/default`, and
 * an offline copy is `build/handoff`.
 */
export function planRelease(values, site, declaration, { env = process.env, dir = configDir(env) } = {}) {
  const declaredBase = declaration.baseUrl !== undefined && declaration.baseUrl !== null && String(declaration.baseUrl).trim() !== ""
  if (values.target !== undefined && values.base !== undefined) {
    die("--target and --base both say where the release is served from; pass one.")
  }
  if (declaration.target !== undefined && declaredBase) {
    die("site.target and site.baseUrl both say where the release is served from; declare one.")
  }

  let name = values.target
  if (name === undefined && values.base === undefined && !declaredBase) {
    name = env.AWT_TARGET || declaration.target || readDefaultTarget(dir) || undefined
  }

  // A wiki that declares no mount and name still has them if this machine registered it. That is
  // only for a target the machine names or a base given on the command line: a project that
  // declares its own base is served at it, and a registration must not move it under a mount.
  const registered = name !== undefined || values.base !== undefined ? registeredAt(loadMachineIfPresent({ dir, die }) ?? { registry: new Map() }, site) : null
  const mount = values.mount ?? declaration.mount ?? registered?.mount
  const wikiName = values.name ?? (mount ? (declaration.self ?? registered?.name) : undefined)

  let target
  if (name !== undefined) {
    const machine = loadMachine({ dir, die })
    const named = machine.targets.get(name)
    if (!named) {
      die(
        `no target "${name}" in ${path.join(dir, "targets.yaml")}` +
          (machine.targets.size ? `; it has ${[...machine.targets.keys()].join(", ")}.` : ", which defines none."),
      )
    }
    target = resolveTarget({ base: named.base, mount, name: wikiName }, declaration, die)
    if (!target.mount) {
      die(`target "${name}" hosts several wikis, so this one needs a mount under it: declare site.mount or pass --mount.`)
    }
    target.targetName = name
  } else {
    target = resolveTarget({ base: values.base, mount: registered ? mount : values.mount, name: registered ? wikiName : values.name }, declaration, die)
  }

  const out = values.out
    ? path.resolve(values.out)
    : values.offline
      ? path.join(site, HANDOFF)
      : publishedDir(site, target?.slug)
  return { target, out, registered }
}

/** The release directory as the registry names it: relative to the site, with a leading `./`. */
function releaseDirIn(site, out) {
  const rel = path.relative(site, out).split(path.sep).join("/")
  return rel.startsWith(".") ? rel : `./${rel}`
}

/** Rewrite the scheme of the target's address in the sitemap, the feed and every page's meta tags. */
export function applyScheme(root, target) {
  if (!target || target.scheme !== "http") return 0
  let changed = 0
  const walk = (d) => {
    for (const e of fs.readdirSync(d, { withFileTypes: true })) {
      const f = path.join(d, e.name)
      if (e.isDirectory()) walk(f)
      else if (f.endsWith(".html") || f.endsWith(".xml")) {
        const before = fs.readFileSync(f, "utf8")
        const after = retargetScheme(before, target)
        if (after !== before) {
          fs.writeFileSync(f, after)
          changed++
        }
      }
    }
  }
  walk(root)
  return changed
}

/**
 * A note for the person receiving the folder, who did not ask for any of this.
 * The zip warning is not hypothetical: Windows lets you browse a zip in place
 * and double-click a file inside it, which extracts that one file to a temp
 * directory, and every relative link in it then points at nothing.
 */
function handoffReadme(title) {
  return `${title}\n${"=".repeat(title.length)}\n
A snapshot of the wiki, for reading offline.

1. EXTRACT this folder from the zip first. Do not open the pages inside the zip
   itself: Windows extracts one page on its own and every link breaks.
2. Open index.html (double-click it). Any browser will do, and nothing has to be
   installed.

Every page is an ordinary HTML file, so the links work with no internet
connection and no server. There is no search box: start at index.html, and use
the links and the trail at the top of each page to move around.
`
}

/**
 * `reindex`, when given, re-emits the link index; `--watch` calls it after each burst of changes to
 * the notes, as `awt site serve` does. Without it the index is whatever was emitted before the start.
 */
export async function publish(argv = process.argv.slice(2), { reindex, beforeBuild } = {}) {
  // When the build began, which is what the release record says it was built from: a note written
  // while it runs is newer than this and shows as stale, instead of looking covered.
  const startedAt = new Date()
  let parsed
  try {
    parsed = parseArgs({
      args: argv,
      options: {
        // No defaults: absent means "find the project", which is not the same as
        // "look for ./docs/wiki". parseArgs cannot tell a default from a value.
        wiki: { type: "string" },
        site: { type: "string" },
        out: { type: "string" },
        base: { type: "string" },
        mount: { type: "string" },
        name: { type: "string" },
        target: { type: "string" },
        offline: { type: "boolean", default: false },
        watch: { type: "boolean", default: false },
        diagrams: { type: "string" },
        nginx: { type: "boolean", default: false },
        "if-stale": { type: "boolean", default: false },
        json: { type: "boolean", default: false },
        "site-config": { type: "string" },
        project: { type: "string" },
        // The dev port, for the wiki's own registry entry: a publish build
        // resolves nothing against it, but the entry is written whole.
        configPort: { type: "string" },
      },
    })
  } catch (e) {
    die(String(e.message))
  }
  const { values } = parsed
  // --json makes stdout one document. The commentary is still worth having --
  // this runs for minutes before it says anything conclusive -- so it moves to
  // stderr rather than being turned off.
  if (values.json) narrateTo(process.stderr)
  const report = (value) => {
    if (values.json) process.stdout.write(`${JSON.stringify(value, null, 1)}\n`)
  }

  const root = values.wiki && values.site ? null : requireProjectRoot(die)
  const wiki = values.wiki ? path.resolve(values.wiki) : path.join(root, "docs/wiki")
  const site = values.site ? path.resolve(values.site) : path.join(root, "site")
  const declaration = readDeclaration(values["site-config"], die)
  if (values.watch) {
    for (const [flag, why] of [
      ["offline", "a handoff copy is built once and opens from disk"],
      ["nginx", "it prints a server block and builds nothing"],
      ["json", "a resident build streams its progress and has no single result to report"],
    ]) {
      if (values[flag]) die(`--watch and --${flag} do not go together: ${why}.`)
    }
  }
  if (values["if-stale"]) {
    for (const [flag, why] of [
      ["watch", "a resident build rebuilds on every save and has no staleness to ask about"],
      ["offline", "a handoff copy has no standing release to compare against"],
      ["nginx", "it prints a server block and builds nothing"],
    ]) {
      if (values[flag]) die(`--if-stale and --${flag} do not go together: ${why}.`)
    }
  }
  if (values.offline && (values.base !== undefined || values.mount !== undefined || values.name !== undefined || values.target !== undefined)) {
    die("--offline builds a copy that opens from disk and has no address; --base, --mount, --name and --target do not apply to it.")
  }
  // Decided before the target is planned: a wiki that was never published has no release to keep
  // current, and planning its target can refuse for the very reason it was never published.
  const skip = (reason, out) => {
    if (values.json) report({ ok: true, skipped: reason, out: out ?? null })
    else say(`not publishing: ${reason}`)
    return 0
  }
  if (values["if-stale"] && values.out === undefined && !fs.existsSync(path.join(site, PUBLISHED))) {
    return skip("this wiki has no release yet; publish once by hand first")
  }
  const { target, out, registered } = planRelease(values, site, declaration)

  for (const [label, p] of [
    ["wiki", wiki],
    ["site", site],
  ]) {
    if (!fs.existsSync(p)) die(`no ${label} directory at ${p}`)
  }

  // Build only if the release for this target is out of date, and never make its first: a first
  // publish decides an address and a host, which is a person's decision and not a hook's.
  let releaseLock = null
  if (values["if-stale"]) {
    const ask = () => staleness({ wiki, out, recordFile: RELEASE_RECORD })
    if (ask().state === "unbuilt") return skip(`no release for this target at ${show(out)}; publish once by hand first`, out)
    if (ask().state === "fresh") return skip("the release is up to date", out)
    releaseLock = takeLock(site)
    if (!releaseLock) return skip("another publish holds the lock", out)
    // Another publish may have finished between the first look and the lock.
    if (ask().state !== "stale") return skip("the release is up to date", out)
    await beforeBuild?.()
  }

  // Pre-rendering is for the handoff copy only. A served site keeps mermaid as
  // Quartz ships it: rendered in the reader's browser, where the diagram follows
  // the page's theme and its text stays searchable.
  const diagrams = values.diagrams ?? (values.offline ? "png" : "none")
  if (!["png", "none"].includes(diagrams)) die(`--diagrams takes png or none, not ${diagrams}`)
  if (diagrams === "png" && !values.offline) {
    die("--diagrams png is only for --offline; a served site renders mermaid in the browser.")
  }

  if (values.nginx) {
    // The server block is the answer, not commentary, so it is the document.
    if (values.json) report({ ok: true, nginx: nginx(out) })
    else say(nginx(out))
    return 0
  }

  if (path.resolve(out) === path.join(site, DEV) || path.resolve(out) === path.join(site, "public")) {
    die(
      "refusing to publish into the dev server's output, build/dev: publish mode over a dev build rewrites\n" +
        `every cross-wiki link to its published form and back. Publish into ${PUBLISHED}/.`,
    )
  }

  // Deliberately not `ensureQuartz`: a release build stays a refusal on stale
  // or missing dependencies rather than an automatic fix, the way `serve`
  // now is. Publishing is the one place this should stay a decision someone
  // makes by running `awt site setup`, not a side effect of building.
  const quartz = quartzDir(site)
  if (!fs.existsSync(quartz)) {
    die(`${quartz} missing; the Quartz install is not set up. Run \`awt site setup\` first.`)
  }
  assertCanonicalConfig(quartz)

  say(`wiki: ${wiki}\nsite: ${site}\n${values.offline ? "handoff" : "published"}: ${out}${target ? `\ntarget: ${target.url}/` : ""}`)
  // The config Quartz reads, derived for a publish build: cross-wiki links to
  // published bases, the declared host as the base URL.
  // A wiki that does not name itself is named by its registration, so a reference to its own prefix
  // is still an ordinary link and not a trip out to its own site.
  const named = declaration.self || !registered || !target?.mount ? declaration : { ...declaration, self: registered.key }
  const derived = await writeSiteConfig(site, quartz, named, {
    projectDir: values.project ? path.resolve(values.project) : path.dirname(site),
    port: Number(values.configPort) || DEFAULT_PORT,
    serving: false,
    target,
    releaseDir: releaseDirIn(site, out),
    machineRegistry: machineRegistryFor(target, die),
    // A handoff copy is read off the disk, away from any host.
    home: values.offline ? null : homeFor(target, { die }),
    die,
  })
  say(`config: ${DERIVED_CONFIG} (${derived.own ? "from this project's own quartz.config.yaml" : "derived"})`)
  const configName = values.offline ? await offlineConfig(site, quartz, derived.config) : null
  say()

  if (values.watch) {
    // Resident: Quartz keeps every parsed note, rebuilds the one that changed, and each finished
    // build is swapped into the release. Nothing below runs; it is the one-shot path.
    const { hotPublish } = await import("./hot.js")
    return hotPublish({ quartz, wiki, out, target, applyScheme, swap, recordPath: RELEASE_RECORD, say, reindex })
  }

  const staging = path.join(path.dirname(out), `.${path.basename(out)}-staging`)
  const prev = path.join(path.dirname(out), `.${path.basename(out)}-prev`)

  // A staging directory left by an interrupted run is half a site, and Quartz
  // would build into it rather than over it for files it no longer emits.
  fs.rmSync(staging, { recursive: true, force: true })

  build(quartz, wiki, staging, configName)
  const measured = verify(staging, values.offline)

  if (values.offline) {
    if (diagrams === "png") {
      try {
        const d = await prerenderDiagrams(staging, quartz, (m) => say(m))
        if (d.diagrams) {
          say(`  ${d.diagrams} mermaid diagrams pre-rendered to PNG, replacing ${d.replaced} code blocks`)
        }
        for (const f of d.failed ?? []) {
          say(`\n⚠ a mermaid diagram would not render, left as its source text:\n    ${f.error}\n    ${f.source.trim().split("\n")[0]}`)
        }
      } catch (e) {
        die(
          `${String(e.message ?? e)}\n\nRun with --diagrams none to build without them; they stay as\n` +
            `source text. The standing copy is untouched; the build is left at ${show(staging)}.`,
        )
      }
    }

    const r = toFileUrls(staging)
    say(
      `  rewrote ${r.rewritten} links to real files, removed ${r.scripts} scripts and ${r.removed} now-unused .js files`,
    )
    if (r.placeholders.length) {
      say(
        `  ${r.neutralised - r.dangling.length} links to ${r.placeholders.length} unwritten notes made unclickable: ` +
          r.placeholders.slice(0, 6).join(", ") +
          (r.placeholders.length > 6 ? `, +${r.placeholders.length - 6} more` : ""),
      )
    }
    if (r.dangling.length) {
      // Not a placeholder and not a missing asset: a link the renderer thought
      // it had resolved. It is broken in the release too, and `awt check` is what
      // says so — this only refuses to hide it.
      say(
        `\n⚠ ${r.dangling.length} link${r.dangling.length === 1 ? "" : "s"} the renderer did not mark broken\n` +
          "  resolve to nothing. They are broken in the served site too; awt check reports them.\n" +
          "  Made unclickable in this copy:",
      )
      for (const d of r.dangling.slice(0, 10)) say(`    ${d}`)
      if (r.dangling.length > 10) say(`    … and ${r.dangling.length - 10} more`)
    }
    if (r.missingAssets.length) {
      die(
        `${r.missingAssets.length} images or stylesheets are missing from the build; not swapping.\n` +
          r.missingAssets.slice(0, 10).map((u) => `  ${u}`).join("\n") +
          `\nThe standing copy is untouched; the build is left at ${show(staging)}.`,
      )
    }
    const v = verifyFileUrls(staging)
    if (v.bad.length) {
      die(
        `${v.bad.length} of ${v.total} references cannot be opened from file://; not swapping.\n` +
          v.bad.slice(0, 10).map((u) => `  ${u}`).join("\n"),
      )
    }
    say(`  ${v.total} clickable references, all of them files a browser can open from disk`)
    const inlined = inlineRootIndex(staging)
    if (inlined) say(`  index.html is ${inlined} itself now, not a redirect to it`)
    fs.writeFileSync(path.join(staging, "README.txt"), handoffReadme(siteTitle(derived.config)))
  }

  if (!values.offline) {
    const retargeted = applyScheme(staging, target)
    if (retargeted) say(`  ${retargeted} files had https:// rewritten to http:// for the target`)
    fs.writeFileSync(path.join(staging, RELEASE_RECORD), `${JSON.stringify(releaseRecord(target, { builtAt: startedAt }), null, 1)}\n`)
  }

  const replaced = swap(staging, out, prev)
  const summary = {
    ok: true,
    mode: values.offline ? "handoff" : "release",
    target: target?.url ?? null,
    wiki,
    site,
    out,
    prev: replaced ? prev : null,
    ...measured,
  }

  say(`\n${values.offline ? "built the handoff copy" : "published"} ${show(out)}`)
  if (replaced) {
    const what = values.offline ? "copy" : "release"
    say(`  previous ${what} kept at ${show(prev)}; roll back with:  mv ${show(prev)} ${show(out)}`)
  }
  if (values.offline) {
    say(
      "\nThe reader extracts the folder and opens index.html; README.txt inside says so.\n" +
        "Search, the graph, the explorer tree and hover previews are absent: they need\n" +
        "JavaScript, which does not run from file://.",
    )
    report(summary)
    return 0
  }

  checkBaseUrl(derived.config, target)
  say(
    "\nServe it with any static host that tries $uri.html before 404:\n" +
      "    try_files $uri $uri.html $uri/index.html =404;\n" +
      "A full nginx server block:  awt site publish --nginx\n" +
      "\nThe graph is verified in two places, neither of them this command:\n" +
      "    awt check                the links on disk\n" +
      "    the awt-links shadow     the rendered pages, during the build above",
  )
  releaseLock?.()
  report(summary)
  return 0
}

/**
 * `awt site verify`: does the release standing at `out` carry the address this project's
 * target says it should? Nothing is built. A release with no record is a different answer
 * from one with the wrong record, since it predates targets or was not made by publish.
 */
export function verifyRelease(argv = process.argv.slice(2)) {
  let parsed
  try {
    parsed = parseArgs({
      args: argv,
      options: {
        wiki: { type: "string" },
        site: { type: "string" },
        out: { type: "string" },
        base: { type: "string" },
        mount: { type: "string" },
        name: { type: "string" },
        target: { type: "string" },
        json: { type: "boolean", default: false },
        "site-config": { type: "string" },
        project: { type: "string" },
        configPort: { type: "string" },
      },
    })
  } catch (e) {
    die(String(e.message))
  }
  const { values } = parsed
  const root = values.site ? null : requireProjectRoot(die)
  const site = values.site ? path.resolve(values.site) : path.join(root, "site")
  const { target, out } = planRelease(values, site, readDeclaration(values["site-config"], die))

  const file = path.join(out, RELEASE_RECORD)
  let record = null
  if (fs.existsSync(file)) {
    try {
      record = JSON.parse(fs.readFileSync(file, "utf8"))
    } catch {
      die(`${show(file)} is not JSON; the release was not written by awt site publish, or was damaged.`)
    }
  } else if (!fs.existsSync(out)) {
    die(`no release at ${show(out)}; run awt site publish for this target first.`)
  }

  const result = compareRecord(record, target)
  const messages = {
    match: `${show(out)} was built for ${result.recorded}/, the target this project names.`,
    "no-target": `${show(out)} was built for ${result.recorded ?? "no address"}/; this project names no target to compare it with.`,
    "no-record": `${show(out)} has no ${RELEASE_RECORD}: it predates targets, or was not made by awt site publish.`,
    mismatch: `${show(out)} was built for ${result.recorded}/ but this project's target is ${result.expected}/.\nRepublish for the target: awt site publish.`,
  }
  if (values.json) process.stdout.write(`${JSON.stringify({ ...result, out }, null, 1)}\n`)
  else say(messages[result.reason])
  return result.ok ? 0 : 1
}
